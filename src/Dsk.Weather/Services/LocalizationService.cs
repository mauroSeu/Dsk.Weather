            ["es"] = CultureInfo.GetCultureInfo("es-ES"),
            ["pt"] = CultureInfo.GetCultureInfo("pt-PT")
        };

        private static readonly Dictionary<string, Dictionary<string, string>> Strings = BuildStrings();

        public static string NormalizeLanguage(string? lang)
        {
            if (string.IsNullOrWhiteSpace(lang))
            {
                return "it";
            }

            string clean = lang.Trim().ToLowerInvariant();
            if (clean.Length > 2 && clean.Contains('-'))
            {
                clean = clean.Substring(0, 2);
            }

            return Strings.ContainsKey(clean) ? clean : "it";
        }

        public static CultureInfo GetCulture(string? lang)
        {
            string code = NormalizeLanguage(lang);
            return Cultures.TryGetValue(code, out CultureInfo? culture)
                ? culture
                : Cultures["it"];
        }

        public static string T(string? lang, string key)
        {
            string code = NormalizeLanguage(lang);
            if (Strings.TryGetValue(code, out Dictionary<string, string>? dict) &&
                dict.TryGetValue(key, out string? value))
            {
                return value;
            }

            if (Strings["it"].TryGetValue(key, out string? fallback))
            {
                return fallback;
            }

            return key;
        }

        public static string Format(string? lang, string key, params object[] args)
        {
            string template = T(lang, key);
            return string.Format(GetCulture(lang), template, args);
        }

        public static string DescribeWmoCode(int code, string? lang = "it")
        {
            string key = code switch
            {
                0 => "wmo_0",
                1 => "wmo_1",
                2 => "wmo_2",
                3 => "wmo_3",
                45 or 48 => "wmo_fog",
                51 or 53 or 55 => "wmo_drizzle",
                56 or 57 => "wmo_freezing_drizzle",
                61 => "wmo_rain_light",
                63 => "wmo_rain_mod",
                65 => "wmo_rain_heavy",
                66 or 67 => "wmo_freezing_rain",
                71 or 73 or 75 or 77 => "wmo_snow",
                80 or 81 or 82 => "wmo_showers",
                85 or 86 => "wmo_snow_showers",
                95 or 96 or 99 => "wmo_storm",
                _ => "wmo_variable"
            };
            return T(lang, key);
        }

        public static string DescribeUvLevel(double uv, string? lang = "it")
        {
            if (uv < 3.0) return T(lang, "uv_low");
            if (uv < 6.0) return T(lang, "uv_mod");
            if (uv < 8.0) return T(lang, "uv_high");
            if (uv < 11.0) return T(lang, "uv_very_high");
            return T(lang, "uv_extreme");
        }

        public static string DescribeWindDirectionCardinal(int degrees, string? lang = "it")
        {
            string code = NormalizeLanguage(lang);
            int norm = ((degrees % 360) + 360) % 360;
            bool useWestW = code is "en" or "de" or "nl";
            string[] dirs = useWestW
                ? new[] { "N", "NE", "E", "SE", "S", "SW", "W", "NW" }
                : new[] { "N", "NE", "E", "SE", "S", "SO", "O", "NO" };
            int idx = (int)Math.Round(norm / 45.0, MidpointRounding.AwayFromZero) % 8;
            return dirs[idx];
        }

        public static string DescribeWeatherModel(WeatherModelPreference model, string? lang = "it")
        {
            return model switch
            {
                WeatherModelPreference.EcmwfIfs => "ECMWF",
                WeatherModelPreference.DwdIcon => "ICON",
                _ => T(lang, "model_auto_short")
            };
        }

